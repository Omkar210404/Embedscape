// Muted cluster palette: equal lightness and chroma in OKLCH, hues spread by the golden
// angle so neighbouring cluster ids never get similar colours.

export type RGB = [number, number, number];

const GOLDEN_ANGLE = 137.508;

export function oklchToSrgb(l: number, c: number, hDeg: number): RGB {
  const h = (hDeg * Math.PI) / 180;
  const a = c * Math.cos(h);
  const b = c * Math.sin(h);
  const l_ = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m_ = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s_ = (l - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const lin: RGB = [
    4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
    -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
    -0.0041960863 * l_ - 0.7034186147 * m_ + 1.707614701 * s_,
  ];
  return lin.map((x) => {
    const v = Math.min(1, Math.max(0, x));
    return v <= 0.0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - 0.055;
  }) as RGB;
}

export function clusterPalette(k: number, lightness = 0.76, chroma = 0.095): RGB[] {
  return Array.from({ length: k }, (_, i) => oklchToSrgb(lightness, chroma, (20 + i * GOLDEN_ANGLE) % 360));
}

export function toCss([r, g, b]: RGB): string {
  const hex = (x: number) => Math.round(x * 255).toString(16).padStart(2, "0");
  return `#${hex(r)}${hex(g)}${hex(b)}`;
}
